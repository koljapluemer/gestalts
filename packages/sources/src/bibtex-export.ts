/**
 * Sources as biblatex `.bib` text, UTF-8 (biber reads it as is). Characters special to LaTeX are escaped, except in
 * URLs and identifiers, which are written exactly.
 */

import { FIELD_NAMES, FIELDS, splitName, type Bib, type FieldName, type FieldValue } from './fields';

/** The first line of a generated .bib: a file that doesn't start with it isn't overwritten. */
export const BIB_HEADER = '% generated by the gestalts source manager; edits will be overwritten';

const SPECIAL: Record<string, string> = {
  '\\': '\\textbackslash{}', '{': '\\{', '}': '\\}', '&': '\\&', '%': '\\%', $: '\\$', '#': '\\#', _: '\\_',
  '~': '\\textasciitilde{}', '^': '\\textasciicircum{}',
};
export const escapeLatex = (s: string) => s.replace(/[\\{}&%$#_~^]/g, (c) => SPECIAL[c]);

/** Braces an item BibTeX would otherwise split. */
const protect = (s: string) => (/,|\band\b/i.test(s) ? `{${s}}` : s);

function name(n: string): string {
  const parts = splitName(n);
  if ('literal' in parts) {
    // an organisation: one unit, never parsed into given and family
    return n.includes(' ') ? `{${escapeLatex(n)}}` : protect(escapeLatex(n));
  }
  const family = [parts.prefix, parts.family].filter(Boolean).join(' ');
  return [family, parts.suffix, parts.given].filter((p): p is string => !!p).map((p) => protect(escapeLatex(p))).join(', ');
}

function value(field: FieldName, v: FieldValue): string {
  const type = FIELDS[field];
  const list = Array.isArray(v) ? v : [String(v)];
  if (type === 'name') return list.map(name).join(' and ');
  if (type === 'list') return list.map((x) => protect(escapeLatex(x))).join(' and ');
  if (type === 'uri' || type === 'verbatim') return String(v);
  return escapeLatex(String(v));
}

export function renderEntry(s: Bib): string {
  const lines: string[] = [];
  if (s.title) lines.push(`  title = {${escapeLatex(s.title)}}`);
  for (const field of FIELD_NAMES) {
    const v = s[field];
    if (v !== undefined && !(Array.isArray(v) && !v.length)) lines.push(`  ${field} = {${value(field, v)}}`);
  }
  return `@${s.entrytype}{${s.key}${lines.length ? `,\n${lines.join(',\n')},\n` : ',\n'}}`;
}

/** Every source, sorted by key, under {@link BIB_HEADER}. */
export function renderBibtex(sources: Bib[]): string {
  const sorted = [...sources].sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  return `${BIB_HEADER}\n\n${sorted.map(renderEntry).join('\n\n')}\n`;
}
