"""Rewrites every decks/stembridge-* from Stembridge's topic exports, one deck per topic.

Stembridge (github.com/koljapluemer/stembridge) generates multiple-choice maths exercises and writes, per topic,
`web/data/<slug>.json` (TeX, concepts, responses, labels) and `web/data/index.json` (its curriculum: concepts and
`part_of` weights). It knows nothing about gestalts; what a topic becomes here is decided only here:

- the topic is an `item-model@1` (`engine: stembridge/<slug>`), with its concepts and responses;
- each exercise is a `multiple-choice@1` made by it, its TeX in `$…$`, practising the model's concepts;
- every concept the topic touches, and what those are part of, is a `concept@2` named `math: <name>`, with a
  `concept-link@1` (`kind: part-of`, `source: stembridge`) per `part_of`. Ids come from names by the rule every deck
  builder shares, so two decks that touch one concept hold the same yml and merge.

Usage: uv run tools/build_decks.py [<stembridge dir>, default ../stembridge]   then publish-data on each deck
(`mise run math-drills:decks` does both).
"""

import hashlib
import json
import shutil
import sys
from pathlib import Path

import yaml

PLUGIN = Path(__file__).resolve().parent.parent
REPO = PLUGIN.parent.parent
PREFIX = "stembridge-"
CLAIM = "stembridge"
TAGS = ["math-drills"]
SOURCE = {
    "id": "source-stembridge", "gestalt": "source@1", "key": "stembridge", "entrytype": "software",
    "title": "Stembridge: maths practice for the Zimbabwe O-level exam", "organization": ["Stembridge"],
    "url": "https://github.com/koljapluemer/stembridge", "license": "CC-BY-4.0",
}


def sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()[:16]


def concept_id(name: str) -> str:
    """The same rule as every deck's builder: `concept-` and the first 16 hex digits of the name's sha256."""
    return "concept-" + sha(name)


def name_of(concept: str) -> str:
    return f"math: {concept}"


def math(tex: str) -> str:
    """TeX as Markdown maths; `$…$` takes no whitespace just inside its ends."""
    return f"${tex.strip()}$"


def write(notes: Path, value: dict) -> str:
    (notes / f"{value['id']}.yml").write_text(yaml.safe_dump(value, allow_unicode=True, sort_keys=False, width=1000), encoding="utf-8")
    return value["id"]


def license_text(title: str) -> str:
    return f"""# {title}

Generated by [Stembridge](https://github.com/koljapluemer/stembridge), maths practice for the Zimbabwe O-level exam,
under [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/). Credit: Stembridge.

Changes: the exercises are reformatted as multiple-choice ymls with their maths as TeX, and linked to concepts.
"""


def build(topic: dict, curriculum: dict, decks: Path) -> str:
    slug = topic["slug"]
    deck = PREFIX + slug.replace("_", "-")
    deck_dir = decks / deck
    notes = deck_dir / "notes"
    if deck_dir.exists():
        shutil.rmtree(deck_dir)
    notes.mkdir(parents=True)

    def ids(weights: dict) -> dict:
        return {concept_id(name_of(c)): w for c, w in sorted(weights.items())}

    # every concept the topic names, and everything those are part of
    touched: set[str] = set()
    todo = [*topic["concepts"], *(c for r in topic["responses"].values() for c in r["concepts"])]
    while todo:
        c = todo.pop()
        if c in touched:
            continue
        if c not in curriculum:
            raise SystemExit(f"{slug}: concept '{c}' isn't in stembridge's curriculum")
        touched.add(c)
        todo += curriculum[c].get("part_of", {})

    members = [write(notes, {**SOURCE})]
    credit = [{"to": SOURCE["id"], "label": "from"}]
    chance = None
    model_id = f"item-model-{deck}"
    items = []
    for e in topic["exercises"]:
        chance = 1 / len(e["options"])
        items.append({
            "id": "mc-" + sha(e["id"]),
            "gestalt": "multiple-choice@1",
            "instruction": e["task"],
            "prompt": math(e["prompt"]),
            "options": [{"text": math(o["tex"]), **({"correct": True} if o["correct"] else {}),
                         **({"response": o["response"]} if o.get("response") else {})} for o in e["options"]],
            "concepts": ids(topic["concepts"]),
            "chance": chance,
            "model": model_id,
            **({"instance": {"labels": e["labels"]}} if e.get("labels") else {}),
            "tags": TAGS,
            "sources": credit,
        })
    members.append(write(notes, {
        "id": model_id,
        "gestalt": "item-model@1",
        "name": slug,
        "title": topic["title"],
        "engine": f"stembridge/{slug}",
        "concepts": ids(topic["concepts"]),
        **({"responses": {k: {"label": r["label"], "concepts": ids(r["concepts"])}
                          for k, r in topic["responses"].items()}} if topic["responses"] else {}),
        **({"chance": chance} if chance else {}),
        "tags": TAGS,
        "sources": credit,
    }))
    members += [write(notes, item) for item in items]
    for c in sorted(touched):
        aliases = curriculum[c].get("aliases", [])
        members.append(write(notes, {"id": concept_id(name_of(c)), "gestalt": "concept@2", "name": name_of(c),
                                     **({"aliases": aliases} if aliases else {})}))
    links = 0
    for c in sorted(touched):
        for whole, weight in sorted(curriculum[c].get("part_of", {}).items()):
            a, b = concept_id(name_of(c)), concept_id(name_of(whole))
            members.append(write(notes, {"id": "link-" + sha(f"{a}|{b}|{CLAIM}"), "gestalt": "concept-link@1",
                                         "from": a, "to": b, "weight": weight, "kind": "part-of", "source": CLAIM}))
            links += 1
    write(notes, {"id": f"deck-{deck}", "gestalt": "deck@1", "name": deck, "title": topic["title"], "members": members})
    (deck_dir / "LICENSE.md").write_text(license_text(topic["title"]), encoding="utf-8")
    print(f"{deck}: {len(items)} exercises, {len(touched)} concepts, {links} links")
    return deck


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO.parent / "stembridge"
    data = src / "web" / "data"
    index = json.loads((data / "index.json").read_text(encoding="utf-8"))
    curriculum = index["curriculum"]
    decks = PLUGIN / "decks"
    decks.mkdir(exist_ok=True)
    built = {build(json.loads((data / g["file"]).read_text(encoding="utf-8")), curriculum, decks)
             for g in index["generators"]}
    for old in decks.glob(PREFIX + "*"):
        if old.name not in built:
            shutil.rmtree(old)
            print(f"{old.name}: removed, its topic is gone")


if __name__ == "__main__":
    main()
